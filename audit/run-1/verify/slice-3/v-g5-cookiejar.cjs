/**
 * v-g5-cookiejar.cjs — VERIFY G-5: four endpoints hand yt-dlp the CANONICAL
 * cookie file while only /api/download uses the protective private copy from
 * server/cookieJar.ts, so a bad write-back can wipe a good saved sign-in.
 *
 * Written from the finding's Steps, from scratch. Evidence:
 *
 *  1. PROVENANCE — for each of the five endpoints, the literal `--cookies`
 *     value the CHILD PROCESS received, read out of my stub's argv.log. Not
 *     inferred from the code: compared byte-for-byte against the canonical
 *     path (<userData>/yt-cookies.txt, which electron/main.cjs puts in
 *     YT_CLIPPER_COOKIE_FILE) and against the /tmp/ytcookie-* private-copy
 *     prefix cookieJar.ts uses.
 *
 *  2. DAMAGE — a real file on disk, before/after bytes and sha256, plus the
 *     product's OWN verdict on whether a sign-in is still there
 *     (window.electronAPI.probeYouTube() -> electron/cookieState.cjs). Three
 *     write-backs a stale session produces: empty, header-only, cookies with
 *     no auth cookie. Run through an unprotected route and then through
 *     /api/download for contrast.
 *
 *  3. CONCURRENCY — two overlapping runs on an unprotected route with a
 *     half-and-pause write-back, to see what the jar looks like afterwards.
 *
 * HONEST BOUND: real yt-dlp's write-back cannot be exercised in this
 * container (YouTube is unreachable). My stub performs the write-back that
 * real yt-dlp documents (YoutubeDL.save_cookies, called from close()) and that
 * server/cookieJar.ts's own header says is the reason it exists. What is
 * measured here is (a) WHICH PATH each endpoint hands over — fully real — and
 * (b) what happens to that file when it is written back — simulated.
 *
 * Run: xvfb-run -a --server-args="-screen 0 1440x900x24" node v-g5-cookiejar.cjs [runLabel]
 */
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const L = require("./v-lib.cjs");

const sha = (p) => { try { return crypto.createHash("sha256").update(fs.readFileSync(p)).digest("hex").slice(0, 16); } catch { return null; } };
const bytes = (p) => { try { return fs.statSync(p).size; } catch { return null; } };

const WRITEBACKS = {
  empty: "",
  headerOnly: "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n",
  noAuthCookie:
    "# Netscape HTTP Cookie File\n\n.youtube.com\tTRUE\t/\tFALSE\t2000000000\tPREF\ttz=UTC\n.youtube.com\tTRUE\t/\tFALSE\t2000000000\tVISITOR_INFO1_LIVE\tabc\n",
};

const URL1 = "https://www.youtube.com/watch?v=stub0000001";

(async () => {
  const runLabel = process.argv[2] || "r1";
  const out = { runLabel, startedAt: new Date().toISOString(), notes: {} };

  const stubRoot = L.makeStub(`g5-${runLabel}`);
  const a = await L.launchMirror({ shape: "public", label: `v-g5-${runLabel}`, stubRoot });
  await a.win.waitForSelector("header", { timeout: 20000 });
  out.apiBase = a.apiBase;

  const jar = path.join(a.userDataDir, "yt-cookies.txt");
  const GOOD = L.cookieJarText();
  const restore = () => fs.writeFileSync(jar, GOOD);
  restore();
  out.canonicalJar = jar;
  out.goodJar = { bytes: bytes(jar), sha: sha(jar) };

  // The product's own answer to "is a sign-in saved?" — same parser the UI uses.
  const probe = () => a.win.evaluate(() => window.electronAPI.probeYouTube());
  out.probeWithGoodJar = await probe();

  // ---------- 1. provenance ---------------------------------------------
  const ENDPOINTS = [
    { name: "/api/info", path: "/api/info", body: { url: URL1, cookiesFromBrowser: "app" } },
    { name: "/api/transcript", path: "/api/transcript", body: { url: URL1, cookiesFromBrowser: "app" } },
    { name: "/api/comments", path: "/api/comments", body: { url: URL1, cookiesFromBrowser: "app" } },
    { name: "/api/auth/youtube/status", path: "/api/auth/youtube/status", body: { browser: "app" } },
    {
      name: "/api/download",
      path: "/api/download",
      body: { url: URL1, quality: "360", format: "mp4", deliver: "path", cookiesFromBrowser: "app", segments: [{ start: 0, end: 3 }] },
    },
    {
      name: "/api/download (quality best)",
      path: "/api/download",
      body: { url: URL1, quality: "best", format: "mp4", deliver: "path", cookiesFromBrowser: "app", segments: [{ start: 0, end: 3 }, { start: 10, end: 13 }] },
    },
  ];

  out.provenance = [];
  for (const e of ENDPOINTS) {
    restore();
    L.clearArgvLog(stubRoot);
    const r = await L.jsonReq({ port: a.port, path: e.path, body: e.body });
    const runs = L.argvLog(stubRoot).filter((x) => x.argv.includes("--cookies"));
    const vals = runs.map((x) => x.argv[x.argv.indexOf("--cookies") + 1]);
    out.provenance.push({
      endpoint: e.name,
      status: r.status,
      runsWithCookies: runs.length,
      canonical: vals.filter((v) => v === jar).length,
      privateCopy: vals.filter((v) => /\/ytcookie-[^/]+\//.test(v)).length,
      other: vals.filter((v) => v !== jar && !/\/ytcookie-[^/]+\//.test(v)),
      sampleValues: [...new Set(vals)].slice(0, 4),
      totalChildRuns: L.argvLog(stubRoot).length,
    });
  }

  // ---------- 2. damage -------------------------------------------------
  out.damage = [];
  for (const route of ["/api/info", "/api/transcript", "/api/comments", "/api/auth/youtube/status", "/api/download"]) {
    for (const [kind, text] of Object.entries(WRITEBACKS)) {
      restore();
      const before = { bytes: bytes(jar), sha: sha(jar) };
      const probeBefore = await probe();
      L.stub(stubRoot, { cookieWriteBack: text, cookieWriteDelayMs: 0 });
      const body =
        route === "/api/auth/youtube/status"
          ? { browser: "app" }
          : route === "/api/download"
            ? { url: URL1, quality: "360", format: "mp4", deliver: "path", cookiesFromBrowser: "app", segments: [{ start: 0, end: 3 }] }
            : { url: URL1, cookiesFromBrowser: "app" };
      const r = await L.jsonReq({ port: a.port, path: route, body });
      // give any trailing write-back a moment to land
      await new Promise((res) => setTimeout(res, 400));
      const after = { bytes: bytes(jar), sha: sha(jar) };
      const probeAfter = await probe();
      out.damage.push({
        route,
        writeBack: kind,
        status: r.status,
        before,
        after,
        jarChanged: before.sha !== after.sha,
        signInBefore: probeBefore.connected === true,
        signInAfter: probeAfter.connected === true,
        signInLost: probeBefore.connected === true && probeAfter.connected !== true,
        probeAfter,
      });
      L.stub(stubRoot, { cookieWriteBack: null });
    }
  }

  // ---------- 3. concurrency -------------------------------------------
  restore();
  L.stub(stubRoot, { cookieWriteBack: GOOD.replace("AKxxSYNTHETIC_SID_VALUE_0123456789abcdef", "AKxxREFRESHED_SID_VALUE_abcdef0123456789"), cookieWriteDelayMs: 250 });
  const beforeConc = { bytes: bytes(jar), sha: sha(jar), lines: fs.readFileSync(jar, "utf8").split("\n").filter((l) => l && !l.startsWith("#")).length };
  const pair = await Promise.all([
    L.jsonReq({ port: a.port, path: "/api/info", body: { url: URL1, cookiesFromBrowser: "app" } }),
    L.jsonReq({ port: a.port, path: "/api/info", body: { url: URL1, cookiesFromBrowser: "app" } }),
  ]);
  await new Promise((res) => setTimeout(res, 800));
  const txt = (() => { try { return fs.readFileSync(jar, "utf8"); } catch { return ""; } })();
  out.concurrency_infoInfo = {
    statuses: pair.map((p) => p.status),
    before: beforeConc,
    after: { bytes: txt.length, sha: sha(jar), cookieLines: txt.split("\n").filter((l) => l && !l.startsWith("#")).length },
    jarText: txt.replace(/AKxx[A-Za-z0-9_]*/g, (m) => m.slice(0, 6) + "…REDACTED"),
    signInAfter: (await probe()).connected === true,
  };

  restore();
  const beforeConc2 = { bytes: bytes(jar), sha: sha(jar) };
  const pair2 = await Promise.all([
    L.jsonReq({ port: a.port, path: "/api/download", body: { url: URL1, quality: "360", format: "mp4", deliver: "path", cookiesFromBrowser: "app", segments: [{ start: 0, end: 3 }] } }),
    L.jsonReq({ port: a.port, path: "/api/download", body: { url: URL1, quality: "360", format: "mp4", deliver: "path", cookiesFromBrowser: "app", segments: [{ start: 5, end: 8 }] } }),
  ]);
  await new Promise((res) => setTimeout(res, 800));
  out.concurrency_downloadDownload = {
    statuses: pair2.map((p) => p.status),
    before: beforeConc2,
    after: { bytes: bytes(jar), sha: sha(jar) },
    jarUnchanged: beforeConc2.sha === sha(jar),
    signInAfter: (await probe()).connected === true,
  };
  L.stub(stubRoot, { cookieWriteBack: null });

  // Where did the write-backs actually land? (the stub logs every one)
  try {
    out.writebackLog = fs.readFileSync(path.join(stubRoot, "writeback.log"), "utf8")
      .split("\n").filter(Boolean).map((l) => JSON.parse(l))
      .reduce((acc, r) => { const k = r.jar === jar ? "canonical" : "privateCopy"; acc[k] = (acc[k] || 0) + 1; return acc; }, {});
  } catch { out.writebackLog = null; }

  await a.close();

  out.summary = {
    canonicalHandedTo: out.provenance.filter((p) => p.canonical > 0).map((p) => p.endpoint),
    privateCopyHandedTo: out.provenance.filter((p) => p.privateCopy > 0).map((p) => p.endpoint),
    routesThatLostTheSignIn: [...new Set(out.damage.filter((d) => d.signInLost).map((d) => d.route))],
    routesThatSurvived: [...new Set(out.damage.filter((d) => !d.signInLost).map((d) => d.route))],
  };
  console.log(JSON.stringify(out.summary, null, 2));
  console.log(L.save(`v-g5-${runLabel}.json`, out));
})();
