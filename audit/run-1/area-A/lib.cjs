/** A valid Netscape cookies.txt carrying a YouTube sign-in. */
function goodCookies({ expires = 2000000000, name = "SID", domain = ".youtube.com", value = "AbCdEf_sid_value_1234567890", crlf = false } = {}) {
  const nl = crlf ? "\r\n" : "\n";
  return [
    "# Netscape HTTP Cookie File",
    "# This file is generated by yt-dlp.  Do not edit.",
    "",
    `${domain}\tTRUE\t/\tTRUE\t${expires}\t${name}\t${value}`,
    `#HttpOnly_${domain}\tTRUE\t/\tTRUE\t${expires}\t__Secure-3PSID\tg.a000${value}`,
    `${domain}\tTRUE\t/\tFALSE\t${expires}\tPREF\tf6=40000000`,
    "",
  ].join(nl);
}

/** Write a fixture cookie file somewhere the test can point the picker at. */
function writeFixture(name, contents) {
  const dir = path.join(OUT, "fixtures");
  fs.mkdirSync(dir, { recursive: true });
  const p = path.join(dir, name);
  if (Buffer.isBuffer(contents)) fs.writeFileSync(p, contents);
  else fs.writeFileSync(p, contents);
  return p;
}

/**
 * Drive the Electron file picker. showOpenDialog is modal in the main process
 * and Playwright cannot click it, so the audit substitutes the dialog's own
 * resolution via electron.evaluate — the product code under test (the IPC
 * handler, validation and commit) still runs for real.
 */
async function stubPicker(app, filePaths) {
  await app.evaluate(({ dialog }, paths) => {
    if (!dialog.__auditOrig) dialog.__auditOrig = dialog.showOpenDialog;
    dialog.showOpenDialog = async () =>
      paths === null
        ? { canceled: true, filePaths: [] }
        : { canceled: false, filePaths: paths };
  }, filePaths);
}

/** Read the app's cookie file straight off disk (userData). */
function cookieFileOf(a) {
  return path.join(a.userDataDir, "yt-cookies.txt");
}

/** Drop a File on the window by synthesising a real DataTransfer drop. */
async function dropCookieText(win, text, { name = "cookies.txt", type = "text/plain" } = {}) {
  await win.evaluate(
    async ({ text, name, type }) => {
      const dt = new DataTransfer();
      dt.items.add(new File([text], name, { type }));
      window.dispatchEvent(
        Object.assign(new Event("dragover", { bubbles: true, cancelable: true }), { dataTransfer: dt }),
      );
      window.dispatchEvent(
        Object.assign(new Event("drop", { bubbles: true, cancelable: true }), { dataTransfer: dt }),
      );
    },
    { text, name, type },
  );
}

/** What the renderer sees back from an IPC call, verbatim. */
async function ipc(win, channel, ...args) {
  return win.evaluate(
    async ({ channel, args }) => {
      const api = window.electronAPI;
      const map = {
        "youtube:probe": () => api.probeYouTube(),
        "youtube:disconnect": () => api.disconnectYouTube(),
        "youtube:importCookies": () => api.importYouTubeCookies(),
        "youtube:importCookiesText": () => api.importYouTubeCookiesText(args[0]),
        "system:browserOrder": () => api.getBrowserOrder(args[0] ?? null),
        "system:defaultBrowser": () => api.getDefaultBrowser(),
      };
      if (!map[channel]) return { __missing: channel };
      try {
        return await map[channel]();
      } catch (e) {
        return { __threw: String(e) };
      }
    },
    { channel, args },
  );
}

/** POST /api/auth/youtube/status from inside the page, on that instance's port. */
async function authStatus(win, browser) {
  return win.evaluate(async (browser) => {
    const r = await fetch(`${window.__API_BASE__}/api/auth/youtube/status`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(browser === undefined ? {} : { browser }),
    });
    return { status: r.status, body: await r.text() };
  }, browser);
}

/** The connect modal's live store state, for assertions the DOM hides. */
async function dump(win) {
  return win.evaluate(() => {
    const root = document.querySelector('[role="dialog"][aria-modal="true"]');
    return {
      modalOpen: Boolean(root),
      heading: document.getElementById("youtube-connect-title")?.textContent ?? null,
      alert: document.querySelector('[role="alert"]')?.textContent ?? null,
      statuses: Array.from(document.querySelectorAll('[role="status"]')).map((e) => e.textContent.trim()),
      reason: document.querySelector("details pre")?.textContent ?? null,
      buttons: Array.from(root?.querySelectorAll("button") ?? []).map((b) => ({
        text: b.textContent.trim().slice(0, 40),
        disabled: b.disabled,
      })),
      focusables: Array.from(
        root?.querySelectorAll("button, select, [href], input, details summary, [tabindex]") ?? [],
      ).length,
      activeEl: document.activeElement
        ? `${document.activeElement.tagName}:${(document.activeElement.textContent || document.activeElement.getAttribute("aria-label") || "").trim().slice(0, 40)}`
        : null,
    };
  });
}

