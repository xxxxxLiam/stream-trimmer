/**
 * Shared helpers for area-A (onboarding and sign-in) audit scripts.
 * Audit-only. Touches no product code.
 */
const fs = require("node:fs");
const path = require("node:path");

const STUB = "/tmp/stub-A";
const OUT = "/home/user/stream-trimmer/audit/out/area-A";

/** Rewrite the yt-dlp stub's script between calls (no relaunch needed). */
function stub(cfg) {
  const base = {
    info: { id: "stub0000001", title: "Stub video", duration: 3600, uploader: "Stub channel" },
    exitCode: 0,
    stderr: "",
    delayMs: 0,
    progress: [0, 50, 100],
    writeMedia: false,
  };
  fs.writeFileSync(path.join(STUB, "stub.json"), JSON.stringify({ ...base, ...cfg }, null, 2));
}

/**
 * Make the auth probe answer `signed_in`. classifyYouTubeAuthOutput only reads
 * yt-dlp's output, and the real `--cookies ... -v` run prints this debug line.
 */
function stubSignedIn(extra = {}) {
  stub({
    exitCode: 1,
    stderr:
      "[debug] Extracted cookies from cookies file\n[debug] Found YouTube account cookies",
    ...extra,
  });
}

