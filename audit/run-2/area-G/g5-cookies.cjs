/**
 * File: g5-cookies.cjs
 * Path: audit/run-2/area-G/g5-cookies.cjs
 * Description: Re-verifies run-1 G-5. All five yt-dlp-running endpoints should
 * now go through server/cookieJar.ts, so the canonical jar is never handed to
 * a child and a bad write-back cannot destroy a saved sign-in.
 *
 *   1  PROVENANCE, from the children's own argv: the literal --cookies value
 *      for /api/info, /api/transcript, /api/comments,
 *      /api/auth/youtube/status and /api/download.
 *   2  DAMAGE: every route x three write-backs a stale session produces
 *      (empty / header-only / cookies with no auth cookie), with the jar's
 *      bytes + sha256 before and after and whether a sign-in is still in it.
 *   3  CONCURRENCY: two calls at once with the write-back split around a
 *      pause, which is what an interleaved save looks like on disk.
 *   4  HYGIENE: are the private copies cleaned up, and does a missing jar
 *      break a call?
 */
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const G = require("./glib.cjs");

const WRITE_BACKS = {
  empty: "",
  headerOnly: "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.\n",
  noAuthCookie:
    "# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t2000000000\tPREF\tf6=40000000\n",
};

const ROUTES = [
  { name: "/api/info", route: "/api/info", body: { url: G.YT_URL, cookiesFromBrowser: "app" } },
  { name: "/api/transcript", route: "/api/transcript", body: { url: G.YT_URL, cookiesFromBrowser: "app" } },
  { name: "/api/comments", route: "/api/comments", body: { url: G.YT_URL, cookiesFromBrowser: "app" } },
  { name: "/api/auth/youtube/status", route: "/api/auth/youtube/status", body: { browser: "app" } },
  {
    name: "/api/download",
    route: "/api/download?jobId=job_cookie",
    body: {
      url: G.YT_URL,
      quality: "360",
      format: "mp4",
      deliver: "path",
      segments: [{ start: 0, end: 2 }],
    },
  },
];

const sha = (f) => crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex").slice(0, 16);
const hasSignIn = (f) => /\bSID\b/.test(fs.readFileSync(f, "utf8"));

function cookieArgs(calls) {
  return calls.map((c) => {
    const i = c.argv.indexOf("--cookies");
    return i >= 0 ? c.argv[i + 1] : null;
  });
}

async function main() {
  const out = { when: new Date().toISOString() };
  const jarDir = fs.mkdtempSync(path.join(require("node:os").tmpdir(), "g2jar-"));
  const jar = path.join(jarDir, "yt-cookies.txt");
  G.writeCookieJar(jar);

  const s = await G.startServer({
    label: "cookies",
    cfg: { duration: 30, authOutput: "Found YouTube account cookies" },
    cookieFile: jar,
  });

  // --- 1. provenance ------------------------------------------------------
  out.provenance = [];
  for (const r of ROUTES) {
    s.configure({ duration: 30, authOutput: "Found YouTube account cookies" });
    s.clearCalls();
    const resp = await s.post(r.route, r.body, { timeout: 300_000 });
    const args = cookieArgs(s.calls());
    out.provenance.push({
      route: r.name,
      status: resp.status,
      runs: args.length,
      cookieArgs: args,
      canonical: args.filter((a) => a === jar).length,
      privateCopy: args.filter((a) => a && a.includes("ytcookie-")).length,
      none: args.filter((a) => a === null).length,
    });
  }

  // best-quality download runs several yt-dlp invocations
  s.clearCalls();
  const best = await s.post(
    "/api/download?jobId=job_cookie_best",
    {
      url: G.YT_URL,
      quality: "best",
      format: "mp4",
      deliver: "path",
      segments: [{ start: 0, end: 2 }],
      cookiesFromBrowser: "app",
    },
    { timeout: 300_000 },
  );
  {
    const args = cookieArgs(s.calls());
    out.provenance.push({
      route: "/api/download (quality best, signed in)",
      status: best.status,
      runs: args.length,
      cookieArgs: args,
      canonical: args.filter((a) => a === jar).length,
      privateCopy: args.filter((a) => a && a.includes("ytcookie-")).length,
      none: args.filter((a) => a === null).length,
    });
  }

  // --- 2. damage ----------------------------------------------------------
  out.damage = [];
  for (const r of ROUTES) {
    for (const [kind, text] of Object.entries(WRITE_BACKS)) {
      G.writeCookieJar(jar);
      const before = { bytes: fs.statSync(jar).size, sha: sha(jar), signedIn: hasSignIn(jar) };
      s.configure({
        duration: 30,
        authOutput: "Found YouTube account cookies",
        cookieWriteBack: text,
      });
      const resp = await s.post(r.route, r.body, { timeout: 300_000 });
      await G.sleep(250);
      const after = {
        exists: fs.existsSync(jar),
        bytes: fs.existsSync(jar) ? fs.statSync(jar).size : null,
        sha: fs.existsSync(jar) ? sha(jar) : null,
        signedIn: fs.existsSync(jar) ? hasSignIn(jar) : false,
      };
      out.damage.push({
        route: r.name,
        writeBack: kind,
        status: resp.status,
        before,
        after,
        jarChanged: before.sha !== after.sha,
        signInLost: before.signedIn && !after.signedIn,
      });
    }
  }

  // --- 3. concurrency, interleaved write-back -----------------------------
  out.concurrency = [];
  for (const pair of [
    ["/api/info", "/api/info"],
    ["/api/info", "/api/transcript"],
    ["/api/auth/youtube/status", "/api/info"],
    ["/api/download", "/api/info"],
  ]) {
    G.writeCookieJar(jar);
    const before = { bytes: fs.statSync(jar).size, sha: sha(jar) };
    s.configure({
      duration: 30,
      authOutput: "Found YouTube account cookies",
      cookieWriteBack:
        "# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tREFRESHED0123456789\n",
      cookieWriteDelayMs: 250,
    });
    const defs = pair.map((n) => ROUTES.find((r) => r.name === n));
    const rs = await Promise.all(
      defs.map((d) => s.post(d.route, d.body, { timeout: 300_000 })),
    );
    await G.sleep(600);
    const text = fs.readFileSync(jar, "utf8");
    out.concurrency.push({
      pair,
      statuses: rs.map((r) => r.status),
      before,
      afterBytes: fs.statSync(jar).size,
      afterSha: sha(jar),
      cookieLines: text.split("\n").filter((l) => l.trim() && !l.startsWith("#")).length,
      signedIn: /\bSID\b/.test(text),
      refreshedValuePresent: text.includes("REFRESHED0123456789"),
    });
  }

  // --- 4. hygiene ---------------------------------------------------------
  out.leftoverPrivateCopies = fs
    .readdirSync(s.serverTmp)
    .filter((n) => n.startsWith("ytcookie-"));
  // a jar that vanishes between the check and the copy
  fs.rmSync(jar, { force: true });
  s.configure({ duration: 30 });
  const noJar = await s.post("/api/info", { url: G.YT_URL, cookiesFromBrowser: "app" });
  out.withNoJar = { status: noJar.status, body: (noJar.body || "").slice(0, 160) };

  out.serverLogCookieLines = s
    .log()
    .split("\n")
    .filter((l) => /cookie|jar/i.test(l))
    .slice(0, 40);
  await s.stop();

  console.log("PROVENANCE");
  for (const p of out.provenance)
    console.log(
      `  ${p.route.padEnd(40)} status=${p.status} runs=${p.runs} canonical=${p.canonical} privateCopy=${p.privateCopy} none=${p.none}`,
    );
  console.log("DAMAGE");
  for (const d of out.damage)
    console.log(
      `  ${d.route.padEnd(26)} ${d.writeBack.padEnd(13)} ${d.before.bytes}->${d.after.bytes} changed=${d.jarChanged} signInLost=${d.signInLost}`,
    );
  console.log("CONCURRENCY");
  for (const c of out.concurrency)
    console.log(
      `  ${c.pair.join(" + ").padEnd(46)} ${c.before.bytes}->${c.afterBytes} lines=${c.cookieLines} signedIn=${c.signedIn} refreshed=${c.refreshedValuePresent}`,
    );
  console.log("leftover private copies:", out.leftoverPrivateCopies);
  console.log("with no jar:", out.withNoJar);
  console.log("results:", G.saveResults("g5-cookies", out));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
